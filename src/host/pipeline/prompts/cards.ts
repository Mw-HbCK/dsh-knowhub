/**
* L1 任务 Prompt：知识卡片提炼（decision / convention / issue / todo）。
*
* 四类各有独立策略段（任务书 §6），在同一条调用内分段呈现，避免调用数膨胀。
* 保留「知识卡片」候选的任务表述（测试替身按此识别本线）。
*/
import { writingRulesBlock} from './writing-rules.js'

export function buildCardsPrompt(topics: string[], context: string): string {
return [
'你是知枢 KnowHub 的项目知识分析器。请只依据下面提供的仓库事实，提炼「知识卡片」候选：结论先行、短小具体的卡片，而不是长篇文档。',
...writingRulesBlock(),
'',
'需要提炼的主题：' + topics.join('、'),
'每个主题提炼 1-3 张卡片；没有足够证据的主题直接跳过，不要硬凑。',
'kind 只能是 decision / convention / issue / todo 之一，四类分别遵循以下策略：',
'',
'记录已经做出的技术或项目决策。正文应尽量包含：决策主题、背景、要解决的问题、考虑过的方案、最终选择、选择原因、取舍与影响、当前状态。材料里没有的字段直接省略或写「未记录」，不得编造方案比较或决策过程。',
'只记录已经形成并在执行的规则（命名、目录、编码、接口、部署、工作约定等）。必须区分两种情况：已在文档或代码中执行的写明约定本身与适用范围；仅仅被提出、尚未落地的只能写成「建议（未落地）：……」。',
'记录真实发生或已确认的问题。正文应尽量包含：问题现象、发生环境、影响范围、定位过程、已确认原因、解决方案、验证结果、当前状态。未经验证的原因推测不得写成结论，只能写入 uncertain。',
'只记录实际存在、尚未完成的事项。正文第一行必须是状态标记，格式固定为「状态：待处理」或「状态：已阻塞」（初始化阶段只允许这两种状态），随后写清要做什么、为什么重要、与哪些文件或模块有关。已经完成的事情不得以 todo 形式出现。',
'',
'每张卡片正文 80-500 字，第一句就是结论。',
'输出 JSON 结构：',
'{"documents":[{"title":"卡片标题","kind":"decision","tags":["标签"],"confidence":0.6,"sources":["相对路径"],"body":"Markdown 正文","uncertain":["待确认事项"]}]}',
'',
'仓库事实：',
context,
].join('\n')
}
